/// Trouve un produit par référence exacte (insensible à la casse)
Produit? getProdByRef(String ref) {
  final r = ref.toUpperCase();
  for (final p in catalogueGed) {
    if (p.ref.toUpperCase() == r) return p;
  }
  return null;
}

/// Info prix pour affichage et chiffrage (essaie d'abord une ref produit, sinon fallback famille)
PrixRef? getPrixInfo(String familleOuRef) {
  final prod = getProdByRef(familleOuRef);
  if (prod != null) {
    return PrixRef(prix: prod.prix, unite: prod.unite, barre: prod.barre);
  }
  return prixRefParFamille[familleOuRef];
}

/// Filtre le catalogue par famille/sous-famille, recherche texte et présence image
List<Produit> filterCatalogue({String? fam, String? q, bool withImg = false}) {
  List<Produit> list = catalogueGed;
  if (fam != null && fam != 'all') {
    if (fam == 'with_img') {
      list = list.where((p) => p.img.isNotEmpty).toList();
    } else {
      list = list.where((p) => p.famille == fam || p.sfam == fam).toList();
    }
  }
  if (withImg) {
    list = list.where((p) => p.img.isNotEmpty).toList();
  }
  if (q != null && q.isNotEmpty) {
    final lq = q.toLowerCase();
    list = list
        .where(
          (p) =>
              p.ref.toLowerCase().contains(lq) ||
              p.nom.toLowerCase().contains(lq) ||
              p.sfam.toLowerCase().contains(lq),
        )
        .toList();
  }
  return list;
}

/// Statistiques du catalogue : total + nombre par famille
class CatalogueStats {
  final int total;
  final Map<String, int> parFamille;
  const CatalogueStats({required this.total, required this.parFamille});
}

CatalogueStats getCatalogueStats() {
  final stats = <String, int>{};
  for (final f in familles) {
    stats[f] = catalogueGed.where((p) => p.famille == f).length;
  }
  return CatalogueStats(total: catalogueGed.length, parFamille: stats);
}

/// Produits d'une famille
List<Produit> getProdsByFamille(String fam) {
  return catalogueGed.where((p) => p.famille == fam).toList();
}

/// Sous-familles distinctes d'une famille (ordre d'apparition dans le catalogue)
List<String> getSousFamilles(String fam) {
  final set = <String>{};
  for (final p in catalogueGed) {
    if (p.famille == fam) set.add(p.sfam);
  }
  return set.toList();
}
